/**
 * Generates supabase/migrations/…_import_content.sql from src/data, preserving
 * ids, URLs (slugs), display order and visibility, and publishes that content
 * as the first site version.
 *
 *   npm run db:generate-import
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { staticSiteContent } from '../src/services/staticContent';
import type { ContentCollection, Listable } from '../src/types';

const OUT = fileURLToPath(new URL('../supabase/migrations/20261126000002_import_content.sql', import.meta.url));
const content = staticSiteContent();

const literal = (value: unknown) => {
  const json = JSON.stringify(value);
  if (json.includes('$json$')) throw new Error('Content contains the reserved marker $json$');
  return `$json$${json}$json$::jsonb`;
};
const text = (s: string) => `'${s.replace(/'/g, "''")}'`;

const rows: string[] = [`  ('profile', 'profile', 0, true, ${literal(content.profile)})`];
const collections: ContentCollection[] = ['projects', 'credentials', 'articles', 'timeline', 'volunteering', 'skills', 'research'];
for (const collection of collections) {
  (content[collection] as Listable[]).forEach((entry, index) => {
    const { id, visible, ...data } = entry as Listable & Record<string, unknown>;
    rows.push(`  (${text(collection)}, ${text(id)}, ${index}, ${visible !== false}, ${literal(data)})`);
  });
}

const sql = `-- Generated by scripts/generate-import.ts from src/data — do not edit by hand.
-- Imports the portfolio content as drafts and publishes it as the first version.
-- Safe to run twice: existing entries and existing published versions are kept.

insert into public.content_entries (collection, id, sort_order, visible, data) values
${rows.join(',\n')}
on conflict (collection, id) do nothing;

insert into public.site_versions (content, files)
select public.build_snapshot(), '{}'
where not exists (select 1 from public.site_versions);
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${rows.length} entries to ${OUT}`);
